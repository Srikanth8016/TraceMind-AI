"""
app/models/event.py — SQLAlchemy ORM model for the ``events`` table.

Why a separate ORM model from the Pydantic schema?
---------------------------------------------------
The Pydantic ``EventCreate`` schema validates HTTP *input*.
The SQLAlchemy ``Event`` model maps to the *database*.
They look similar but serve different contracts:

  - Pydantic enforces API field rules (min_length, enum, etc.)
  - SQLAlchemy maps Python attributes to SQL columns

Keeping them separate means we can evolve the API and the DB schema
independently without surprise coupling.

Column design
-------------
- ``id``          UUID primary key generated by PostgreSQL (gen_random_uuid()).
                  Using DB-generated UUIDs avoids collision in distributed inserts
                  and lets the DB be the authority on IDs.
- ``service_name``, ``environment``, ``level``, ``message``
                  Non-nullable text columns with lengths mirroring Pydantic limits.
- ``timestamp``   TIMESTAMPTZ — always store with timezone in PostgreSQL.
                  Storing as UTC and converting at the application layer is safest.
- ``created_at``  TIMESTAMPTZ with ``server_default=func.now()`` — PostgreSQL fills
                  this automatically; the application never sets it explicitly.
"""

import uuid

from sqlalchemy import DateTime, ForeignKey, String, Text, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class Event(Base):
    """
    ORM model representing a single ingested event stored in ``events`` table.

    Attributes
    ----------
    id : uuid.UUID
        Primary key, generated by PostgreSQL (gen_random_uuid()).
    service_name : str
        Name of the service that produced this event.
    environment : str
        Deployment environment (production, staging, dev, …).
    level : str
        Severity string — one of DEBUG / INFO / WARNING / ERROR / CRITICAL.
    message : str
        Human-readable description of the event.
    timestamp : datetime
        Timezone-aware datetime sent by the client.
    created_at : datetime
        Timezone-aware datetime set by the database when the row is inserted.
    """

    __tablename__ = "events"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
        # gen_random_uuid() is built into PostgreSQL 13+; no extension required.
    )

    service_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    environment: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )

    level: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        # We do *not* use a PG ENUM type here to keep migrations simpler;
        # the enum constraint is enforced at the application layer by Pydantic.
    )

    message: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    timestamp: Mapped[object] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    created_at: Mapped[object] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        # ``server_default`` tells SQLAlchemy NOT to include this column in
        # INSERT statements — PostgreSQL fills it automatically.
        # ``default`` is the Python-side fallback used by SQLite in tests.
        default=func.now(),
        nullable=False,
    )

    incident_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("incidents.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # Relationship to the correlated incident (Milestone 7)
    incident = relationship("Incident", back_populates="events")

    def __repr__(self) -> str:
        return (
            f"<Event id={self.id!s} service={self.service_name!r} "
            f"level={self.level!r} incident_id={self.incident_id!s} ts={self.timestamp!r}>"
        )

"""
app/models/incident.py — SQLAlchemy ORM model for grouped incidents.

Milestone 7: Deterministic incident grouping and event correlation.

Design Decisions
----------------
1. **Incident Identity & Fingerprint**:
   Incidents represent unique operational issues identified by a SHA-256 fingerprint
   computed from (service_name, environment, normalized_error_signature).
2. **Lifecycle States**:
   OPEN -> ACKNOWLEDGED -> RESOLVED.
   Only OPEN and ACKNOWLEDGED incidents receive incoming events within the correlation window.
   A resolved incident will not absorb new events; a new incident is created if the error recurs.
3. **Correlation Window & Counters**:
   Each incident tracks `first_seen_at`, `last_seen_at`, and `event_count`.
   When a new event correlates, `last_seen_at` updates and `event_count` increments.
4. **Relationship to Events**:
   1-to-many relationship via `events.incident_id` foreign key.
"""

from datetime import datetime
from enum import Enum
import uuid

from sqlalchemy import DateTime, Integer, String, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class IncidentStatus(str, Enum):
    """Lifecycle states of an incident."""
    OPEN = "OPEN"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"


class Incident(Base):
    """
    ORM model representing a correlated group of error events.

    Attributes
    ----------
    id : uuid.UUID
        Primary key, generated by PostgreSQL or Python fallback.
    service_name : str
        Source microservice where the incident originated.
    environment : str
        Deployment environment (e.g. production, staging).
    fingerprint : str
        Deterministic 64-character SHA-256 hex digest.
    title : str
        Human-readable summary or normalized signature of the incident.
    severity : str
        Incident severity (ERROR or CRITICAL). Escalates if CRITICAL event seen.
    status : str
        Current lifecycle state (OPEN, ACKNOWLEDGED, RESOLVED).
    first_seen_at : datetime
        Timestamp of the earliest event linked to this incident.
    last_seen_at : datetime
        Timestamp of the most recent event linked to this incident.
    event_count : int
        Running tally of events correlated to this incident.
    created_at : datetime
        Database insertion timestamp.
    updated_at : datetime
        Last update timestamp.
    """
    __tablename__ = "incidents"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
        default=uuid.uuid4,
    )

    service_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        index=True,
    )

    environment: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        index=True,
    )

    fingerprint: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        index=True,
    )

    title: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )

    severity: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="ERROR",
        index=True,
    )

    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default=IncidentStatus.OPEN.value,
        index=True,
    )

    first_seen_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    last_seen_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )

    event_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=1,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        default=func.now(),
        nullable=False,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    # 1-to-many relationship: an incident has many events
    events = relationship("Event", back_populates="incident", lazy="select")

    # 1-to-many relationship: an incident can have multiple investigation jobs
    investigation_jobs = relationship("InvestigationJob", back_populates="incident", lazy="select")

    def __repr__(self) -> str:
        return (
            f"<Incident id={self.id!s} service={self.service_name!r} "
            f"severity={self.severity!r} count={self.event_count} status={self.status!r}>"
        )
